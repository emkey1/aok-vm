#!/usr/bin/env python3
# avgen.py > avstress.c -- the AltiVec test for the PowerPC front end: every AltiVec insn of a G4, each form of
# its immediate, in a function of its own that loads three operand vectors, VSCR and CR6, runs the insn into a
# register that held something, and stores the result, VSCR and the CR. Each is called ROUNDS times on operands
# made to sit where the gadgets draw their lines, and a hash of all it left is printed, a line an insn. Two
# engines must print the same lines.
import sys
ROUNDS = int(sys.argv[1]) if len(sys.argv) > 1 else 3000
stubs = []          # (name, the insn's text)
def add(name, text): stubs.append((name, text))

three = """vaddubm vadduhm vadduwm vaddcuw vsububm vsubuhm vsubuwm vsubcuw vmaxub vmaxuh vmaxuw vmaxsb vmaxsh vmaxsw
vminub vminuh vminuw vminsb vminsh vminsw vavgub vavguh vavguw vavgsb vavgsh vavgsw vrlb vrlh vrlw vslb vslh vslw vsl
vsrb vsrh vsrw vsr vsrab vsrah vsraw vand vandc vor vxor vnor vmuloub vmulouh vmulosb vmulosh vmuleub vmuleuh vmulesb
vmulesh vmrghb vmrghh vmrghw vmrglb vmrglh vmrglw vslo vsro vpkuhum vpkuwum vaddubs vadduhs vadduws vaddsbs vaddshs
vaddsws vsububs vsubuhs vsubuws vsubsbs vsubshs vsubsws vsum4ubs vsum4sbs vsum4shs vsum2sws vsumsws vpkuhus vpkuwus
vpkshus vpkswus vpkshss vpkswss vpkpx vaddfp vsubfp vmaxfp vminfp
vcmpequb vcmpequh vcmpequw vcmpgtub vcmpgtuh vcmpgtuw vcmpgtsb vcmpgtsh vcmpgtsw vcmpeqfp vcmpgefp vcmpgtfp
vcmpbfp""".split()
for n in three:
    add(n, '%s 5,2,3' % n)
    add(n + '_dd', '%s 2,2,3' % n)          # the result over an operand
    add(n + '_aa', '%s 5,3,3' % n)          # one register twice
    if n.startswith('vcmp'):
        add(n + '_rc', '%s. 5,2,3' % n)
        add(n + '_rc_dd', '%s. 3,2,3' % n)
for n in 'vupkhsb vupkhsh vupklsb vupklsh vupkhpx vupklpx vrefp vrsqrtefp vexptefp vlogefp vrfin vrfiz vrfip vrfim'.split():
    add(n, '%s 5,3' % n)
    add(n + '_dd', '%s 3,3' % n)
for n in 'vmhaddshs vmhraddshs vmladduhm vmsumubm vmsummbm vmsumuhm vmsumuhs vmsumshm vmsumshs vsel vperm vmaddfp vnmsubfp'.split():
    add(n, '%s 5,2,3,4' % n)
    add(n + '_dd', '%s 4,2,3,4' % n)
    add(n + '_da', '%s 2,2,3,4' % n)
    add(n + '_ab', '%s 5,2,2,4' % n)
for i in range(16): add('vspltb_%d' % i, 'vspltb 5,3,%d' % i)
for i in range(8): add('vsplth_%d' % i, 'vsplth 5,3,%d' % i)
for i in range(4): add('vspltw_%d' % i, 'vspltw 5,3,%d' % i)
add('vspltw_dd', 'vspltw 3,3,1')
for n in ('vspltisb', 'vspltish', 'vspltisw'):
    for i in range(-16, 16): add('%s_%s' % (n, str(i).replace('-', 'm')), '%s 5,%d' % (n, i))
for i in range(16):
    add('vsldoi_%d' % i, 'vsldoi 5,2,3,%d' % i)
    add('vsldoi_%d_dd' % i, 'vsldoi 3,2,3,%d' % i)
for n in ('vcfsx', 'vcfux', 'vctsxs', 'vctuxs'):
    for i in range(32): add('%s_%d' % (n, i), '%s 5,3,%d' % (n, i))
    add(n + '_dd', '%s 3,3,7' % n)
# r10 holds a number from the operands: an address's low bits
add('lvsl', 'lvsl 5,10,%0')
add('lvsl_0', 'lvsl 5,0,10')
add('lvsr', 'lvsr 5,10,%0')
add('lvsr_0', 'lvsr 5,0,10')
for n in ('lvebx', 'lvehx', 'lvewx'):
    add(n, 'andi. 10,10,15\n %s 5,10,%%0' % n)
for n in ('stvebx', 'stvehx', 'stvewx'):
    add(n, 'andi. 10,10,15\n %s 3,10,%%0' % n)
add('mfvscr', 'mfvscr 5')
add('mtvscr', 'mtvscr 3')

print('/* Generated by avgen.py: see it for what this is. */')
print('#define ROUNDS %d' % ROUNDS)
print(r'''#include <stdio.h>
#include <stdint.h>
#include <string.h>

typedef struct {
    uint32_t a[4], b[4], c[4], vscr_in[4], out[4], vscr_out[4], ra[4], rb[4], rc[4];
    uint32_t cr_in, cr_out, x, pad;
} __attribute__((aligned(16))) IO;

/*
 * v2, v3, v4 = a, b, c; v5 = out as it was; VSCR and CR6 as given; r10 = x. Then the insn, and every vector
 * register it could have written, VSCR and the CR back to memory.
 */
#define STUB(name, text) \
    static void __attribute__((noinline)) f_##name(IO *io) \
    { \
        __asm__ volatile("lvx 2,0,%0\n li 9,16\n lvx 3,9,%0\n li 9,32\n lvx 4,9,%0\n li 9,48\n lvx 6,9,%0\n" \
                         " mtvscr 6\n li 9,64\n lvx 5,9,%0\n lwz 9,144(%0)\n mtcrf 2,9\n lwz 10,152(%0)\n" \
                         " " text "\n" \
                         " li 9,64\n stvx 5,9,%0\n mfvscr 6\n li 9,80\n stvx 6,9,%0\n mfcr 9\n stw 9,148(%0)\n" \
                         " li 9,96\n stvx 2,9,%0\n li 9,112\n stvx 3,9,%0\n li 9,128\n stvx 4,9,%0\n" \
                         : : "b"(io) : "r9", "r10", "cr0", "cr6", "v2", "v3", "v4", "v5", "v6", "memory"); \
    }
''')
for n, t in stubs:
    print('STUB(%s, "%s")' % (n, t.replace('\n', '\\n')))
print('static const struct { const char *name; void (*f)(IO *); } stubs[] = {')
for n, t in stubs:
    print('    { "%s", f_%s },' % (n, n))
print('};')
print(r'''
static uint64_t s = 0x9e3779b97f4a7c15ull;
static uint64_t rnd(void) { s ^= s << 13; s ^= s >> 7; s ^= s << 17; return s; }
static uint64_t mix(uint64_t h, uint64_t v) { h ^= v; h *= 0x100000001b3ull; return h ^ (h >> 29); }

/* Singles where the FP gadgets draw their lines, and integers where sums and narrowings saturate. */
static const uint32_t fspecial[] = {
    0x00000000, 0x80000000, 0x7f800000, 0xff800000, 0x7fc00000, 0xffc00000, 0x7f800001, 0xffa00000, 0x7fffffff,
    0x00000001, 0x80000001, 0x007fffff, 0x807fffff, 0x00800000, 0x80800000, 0x00800001, 0x80800001, 0x00400000,
    0x01000000, 0x81000000, 0x00ffffff, 0x7f7fffff, 0xff7fffff, 0x7f000000, 0x3f800000, 0xbf800000, 0x3f000000,
    0xbf000000, 0x3fc00000, 0xbfc00000, 0x40000000, 0x40200000, 0xc0200000, 0x3effffff, 0x3f000001, 0x3f7fffff,
    0x4f000000, 0xcf000000, 0x4effffff, 0xceffffff, 0x4f800000, 0xcf800000, 0x4f7fffff, 0xcf000001, 0x4b800000,
    0x4b000000, 0x4affffff, 0xcb000000, 0x5f000000, 0xdf000000, 0x1f800000, 0x9f800000, 0x20000000, 0x1fffffff,
    0x00fffffe, 0x80fffffe, 0x01800000, 0x33800000, 0xb3800000, 0x34000000,
};
static const uint32_t ispecial[] = {
    0, 1, 2, 0xffffffff, 0xfffffffe, 0x7fffffff, 0x80000000, 0x80000001, 0x7ffffffe, 0x00007fff, 0x00008000,
    0xffff8000, 0xffff7fff, 0x0000ffff, 0x00010000, 0x7fff7fff, 0x80008000, 0x7f7f7f7f, 0x80808080, 0xff00ff00,
    0x00ff00ff, 0x007f0080, 0x00800080, 0xff80ff7f, 0x01010101, 0xfefefefe, 0x00000080, 0x0000007f, 0x000000ff,
    0x00000100, 0xffffff80, 0xffffff7f, 0x40004000, 0xc000c000, 0x7fff8000, 0x80007fff,
};

static uint32_t word(void)
{
    uint64_t r = rnd();
    unsigned k = r % 100;
    uint32_t v = r >> 32;

    if (k < 30) {
        return v;                                               /* any bits */
    } else if (k < 50) {
        return fspecial[(r >> 8) % (sizeof(fspecial) / sizeof(fspecial[0]))];
    } else if (k < 65) {
        return ispecial[(r >> 8) % (sizeof(ispecial) / sizeof(ispecial[0]))];
    } else if (k < 75) {
        return (v & 0x807fffff) | (((r >> 8) % 6) << 23);       /* at the bottom of the range */
    } else if (k < 82) {
        return (v & 0x807fffff) | ((0x3d + (r >> 8) % 8) << 23); /* whose products are there */
    } else if (k < 90) {
        return (v & 0x80000007) | ((0x7c + (r >> 8) % 8) << 23) | ((v >> 8 & 3) << 21); /* small, few bits */
    } else if (k < 95) {
        return (v & 0x807fffff) | ((0x9c + (r >> 8) % 6) << 23); /* around 2^31 */
    }
    return (uint32_t)(int32_t)(int8_t)v;                        /* a small integer */
}

/*
 * The same without NaNs and denormals, which send a whole vector to C: every other round is of these, so that
 * the gadgets' own arithmetic is what gets tested, with results on both sides of the least normal number.
 */
static uint32_t clean(void)
{
    static const uint32_t some[] = {
        0x00000000, 0x80000000, 0x7f800000, 0xff800000, 0x00800000, 0x80800000, 0x00800001, 0x80800001,
        0x01000000, 0x81000000, 0x00ffffff, 0x7f7fffff, 0xff7fffff, 0x3f800000, 0xbf800000, 0x3f000000,
        0xbf000000, 0x3fc00000, 0x40200000, 0xc0200000, 0x3effffff, 0x3f000001, 0x4f000000, 0xcf000000,
        0x4effffff, 0x4f800000, 0xcf800000, 0x4f7fffff, 0xcf000001, 0x4b000000, 0x4affffff, 0x1f800000,
        0x20000000, 0x1fffffff, 0x00fffffe, 0x33800000,
    };
    uint64_t r = rnd();
    unsigned k = r % 100;
    uint32_t v = r >> 32;

    if (k < 25) {
        return (v & 0x807fffff) | ((1 + (r >> 8) % 253) << 23);     /* any normal number */
    } else if (k < 45) {
        return some[(r >> 8) % (sizeof(some) / sizeof(some[0]))];
    } else if (k < 60) {
        return (v & 0x807fffff) | ((1 + (r >> 8) % 5) << 23);       /* at the bottom of the range */
    } else if (k < 72) {
        return (v & 0x807fffff) | ((0x3d + (r >> 8) % 8) << 23);    /* whose products are there */
    } else if (k < 85) {
        return (v & 0x80000007) | ((0x7c + (r >> 8) % 8) << 23) | ((v >> 8 & 3) << 21);
    } else if (k < 93) {
        return (v & 0x807fffff) | ((0x9c + (r >> 8) % 6) << 23);    /* around 2^31 */
    }
    return (v & 0x80000000) | ((0x7f + (r >> 8) % 6) << 23);        /* a power of two */
}

int main(void)
{
    static IO io;
    uint64_t all = 0;

    for (unsigned n = 0; n < sizeof(stubs) / sizeof(stubs[0]); n++) {
        uint64_t h = 0xcbf29ce484222325ull;

        for (int round = 0; round < ROUNDS; round++) {
            uint64_t r = rnd();

            for (int i = 0; i < 4; i++) {
                io.a[i] = round & 1 ? clean() : word();
                io.b[i] = round & 1 ? clean() : word();
                io.c[i] = round & 1 ? clean() : word();
                io.out[i] = rnd();
                io.vscr_in[i] = 0;
                io.vscr_out[i] = 0;
                io.ra[i] = io.rb[i] = io.rc[i] = 0;
            }
            /* operands that cancel, or nearly: b = +-a, or a beside it; c = 1 */
            for (int i = 0; i < 4; i++) {
                unsigned k = (r >> (8 + 4 * i)) & 15;

                if (k == 0) {
                    io.b[i] = io.a[i];
                } else if (k == 1) {
                    io.b[i] = io.a[i] ^ 0x80000000;
                } else if (k == 2) {
                    io.b[i] = (io.a[i] ^ 0x80000000) + 1;
                } else if (k == 3) {
                    io.c[i] = 0x3f800000;
                    io.b[i] = io.a[i] ^ 0x80000000;
                } else if (k == 4) {
                    io.c[i] = 0x3f800000;
                    io.b[i] = io.a[i];
                } else if (k == 5) {
                    io.b[i] = io.a[i] + ((r >> 30) & 3) - 1;
                }
            }
            /* VSCR: NJ three times in four, as Mac OS X has it, and SAT as it was left or not */
            io.vscr_in[3] = ((r & 3) ? 0x10000 : 0) | ((r >> 2) & 1);
            io.cr_in = ((r >> 3) & 15) << 4;
            io.cr_out = 0;
            io.x = (r >> 40) & 0xff;
            stubs[n].f(&io);
            for (unsigned i = 0; i < sizeof(io) / 4; i++) {
                h = mix(h, ((uint32_t *)&io)[i]);
            }
        }
        fprintf(stderr, "AVSTRESS %s %016llx\n", stubs[n].name, (unsigned long long)h);
        all = mix(all, h);
    }
    fprintf(stderr, "AVSTRESS all %u insns %016llx\n", (unsigned)(sizeof(stubs) / sizeof(stubs[0])),
            (unsigned long long)all);
    return 0;
}''')
